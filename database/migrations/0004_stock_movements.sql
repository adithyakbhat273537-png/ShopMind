create table if not exists public.stock_movements (
  movement_id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(product_id) on delete restrict,
  changed_by uuid references public.profiles(id) on delete set null,
  movement_type text not null check (movement_type in ('stock_in', 'stock_out', 'adjustment')),
  quantity integer not null check (quantity > 0),
  previous_quantity integer not null check (previous_quantity >= 0),
  new_quantity integer not null check (new_quantity >= 0),
  note text,
  created_at timestamptz not null default now()
);
create index if not exists stock_movements_product_date_idx on public.stock_movements(product_id, created_at desc);
alter table public.stock_movements enable row level security;
drop policy if exists "Admins read stock movements" on public.stock_movements;
create policy "Admins read stock movements" on public.stock_movements for select to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'));
