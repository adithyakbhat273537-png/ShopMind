create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  category_name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  product_id bigint generated by default as identity primary key,
  product_name text not null,
  sku text not null unique,
  barcode text unique,
  category_id bigint references public.categories(category_id) on delete set null,
  brand text,
  description text,
  purchase_price numeric(12,2) check (purchase_price is null or purchase_price >= 0),
  price numeric(12,2) not null check (price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  reorder_level integer not null default 0 check (reorder_level >= 0),
  rack_number text,
  shelf_number text,
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category_id);
create index if not exists products_name_search_idx on public.products using gin (to_tsvector('simple', coalesce(product_name,'') || ' ' || coalesce(brand,'') || ' ' || coalesce(sku,'') || ' ' || coalesce(description,'')));
alter table public.categories enable row level security;
alter table public.products enable row level security;
drop policy if exists "Catalogue categories readable" on public.categories;
create policy "Catalogue categories readable" on public.categories for select to anon, authenticated using (true);
drop policy if exists "Catalogue products readable" on public.products;
create policy "Catalogue products readable" on public.products for select to anon, authenticated using (true);
