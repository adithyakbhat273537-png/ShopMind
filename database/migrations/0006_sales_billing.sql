create table if not exists public.orders (
  order_id bigint generated by default as identity primary key,
  order_number text not null unique default ('SM-' || upper(substr(gen_random_uuid()::text,1,8))),
  customer_id uuid references public.profiles(id) on delete set null,
  customer_name text not null,
  customer_mobile text not null,
  customer_email text,
  order_status text not null default 'completed' check (order_status in ('draft','completed','cancelled')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  tax_amount numeric(12,2) not null default 0 check (tax_amount >= 0),
  total numeric(12,2) not null check (total >= 0),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  order_item_id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(order_id) on delete cascade,
  product_id bigint not null references public.products(product_id) on delete restrict,
  product_name text not null,
  sku text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);
create table if not exists public.invoices (
  invoice_id bigint generated by default as identity primary key,
  invoice_number text not null unique default ('INV-' || upper(substr(gen_random_uuid()::text,1,8))),
  order_id bigint not null unique references public.orders(order_id) on delete restrict,
  issued_by uuid references public.profiles(id) on delete set null,
  issued_at timestamptz not null default now()
);
create index if not exists orders_customer_mobile_idx on public.orders(customer_mobile);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.invoices enable row level security;
drop policy if exists "Staff and owners read orders" on public.orders;
create policy "Staff and owners read orders" on public.orders for select to authenticated
using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role in ('admin','staff')) or customer_id=(select auth.uid()));
drop policy if exists "Staff and owners read order items" on public.order_items;
create policy "Staff and owners read order items" on public.order_items for select to authenticated
using (exists(select 1 from public.orders o join public.profiles p on p.id=(select auth.uid()) where o.order_id=order_items.order_id and p.role in ('admin','staff')) or exists(select 1 from public.orders o where o.order_id=order_items.order_id and o.customer_id=(select auth.uid())));
drop policy if exists "Staff and owners read invoices" on public.invoices;
create policy "Staff and owners read invoices" on public.invoices for select to authenticated
using (exists(select 1 from public.orders o join public.profiles p on p.id=(select auth.uid()) where o.order_id=invoices.order_id and p.role in ('admin','staff')) or exists(select 1 from public.orders o where o.order_id=invoices.order_id and o.customer_id=(select auth.uid())));
