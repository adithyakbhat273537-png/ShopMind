-- VisionRack: private image storage and persistent detection runs.
create table if not exists public.detection_results (
  detection_id bigint generated by default as identity primary key,
  image_path text not null,
  processed_image_path text,
  source_filename text not null,
  model_name text,
  detections jsonb not null default '[]'::jsonb,
  inference_ms integer,
  status text not null default 'completed' check (status in ('completed', 'failed')),
  error_message text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists detection_results_created_at_idx
  on public.detection_results(created_at desc, detection_id desc);
create index if not exists detection_results_created_by_idx
  on public.detection_results(created_by, created_at desc);

alter table public.detection_results enable row level security;
drop policy if exists "ShopMind staff read VisionRack results" on public.detection_results;
create policy "ShopMind staff read VisionRack results"
  on public.detection_results for select to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role in ('admin', 'staff')
  ));
drop policy if exists "ShopMind staff create VisionRack results" on public.detection_results;
create policy "ShopMind staff create VisionRack results"
  on public.detection_results for insert to authenticated
  with check (
    created_by = (select auth.uid()) and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role in ('admin', 'staff')
    )
  );

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('visionrack-images', 'visionrack-images', false, 10485760,
        array['image/jpeg', 'image/png', 'image/webp']::text[])
on conflict (id) do update set public = false, file_size_limit = 10485760,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "ShopMind staff read VisionRack images" on storage.objects;
create policy "ShopMind staff read VisionRack images"
  on storage.objects for select to authenticated
  using (bucket_id = 'visionrack-images' and exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role in ('admin', 'staff')
  ));
drop policy if exists "ShopMind staff upload VisionRack images" on storage.objects;
create policy "ShopMind staff upload VisionRack images"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'visionrack-images' and (storage.foldername(name))[1] = (select auth.uid())::text
    and exists (select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role in ('admin', 'staff')));
drop policy if exists "ShopMind staff delete own VisionRack images" on storage.objects;
create policy "ShopMind staff delete own VisionRack images"
  on storage.objects for delete to authenticated
  using (bucket_id = 'visionrack-images' and (storage.foldername(name))[1] = (select auth.uid())::text
    and exists (select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role in ('admin', 'staff')));
